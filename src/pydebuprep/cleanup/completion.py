"""bash and zsh completion scripts for pydebuprep-cleanup, generated from its parser.

The packaged files under completions/ are the output of these functions; a test fails
if they drift. `make generated` writes them with main().
"""

from __future__ import annotations

import argparse
import sys

from pydebuprep.cleanup.cli import build_parser
from pydebuprep.cleanup.kernels import KEEP_MAX
from pydebuprep.completion import _help, _safe, _zsh_escape

PROG = "pydebuprep-cleanup"
HEADER = "generated by `make generated` (pydebuprep.cleanup.completion); do not edit by hand"
# Installed and leftover package names, for --keep-package (a read-only dpkg query).
PACKAGES = "dpkg-query -W -f='${binary:Package}\\n' 2>/dev/null"
KEEP_VALUES = " ".join(str(n) for n in range(1, KEEP_MAX + 1))


def _actions() -> list[argparse.Action]:
    return [a for a in build_parser()._actions if a.option_strings]


def _exclusive() -> dict[str, list[str]]:
    excluded: dict[str, list[str]] = {}
    for group in build_parser()._mutually_exclusive_groups:
        flags = [f for a in group._group_actions for f in a.option_strings]
        for flag in flags:
            excluded[flag] = [f for f in flags if f != flag]
    return excluded


def bash_completion() -> str:
    words = " ".join(_safe(f) for a in _actions() for f in a.option_strings if f.startswith("--"))
    return f"""# bash completion for {PROG} -- {HEADER.format(name="bash")}

_pydebuprep_cleanup() {{
    local cur=${{COMP_WORDS[COMP_CWORD]}} prev=${{COMP_WORDS[COMP_CWORD-1]}}
    case $prev in
        --config)
            mapfile -t COMPREPLY < <(compgen -f -- "$cur")
            return
            ;;
        --keep)
            mapfile -t COMPREPLY < <(compgen -W "{KEEP_VALUES}" -- "$cur")
            return
            ;;
        --keep-package)
            mapfile -t COMPREPLY < <(compgen -W "$({PACKAGES})" -- "$cur")
            return
            ;;
    esac
    mapfile -t COMPREPLY < <(compgen -W "{words}" -- "$cur")
}}

complete -F _pydebuprep_cleanup {PROG}
"""


def _zsh_spec(action: argparse.Action, excluded: dict[str, list[str]]) -> str:
    long_flags = [f for f in action.option_strings if f.startswith("--")]
    flag = _safe(long_flags[0])
    others = sorted({o for f in action.option_strings for o in excluded.get(f, [])})
    exclusive = f"({' '.join(others)})" if others else ""
    repeat = "*" if isinstance(action, argparse._AppendAction) else ""
    text = _zsh_escape(_help(action, PROG))
    value = ""
    if flag == "--config":
        value = ":file:_files"
    elif flag == "--keep":
        value = f":N:({KEEP_VALUES})"
    elif flag == "--keep-package":
        value = ":package:_pydebuprep_cleanup_packages"
    return f"'{exclusive}{repeat}{flag}[{text}]{value}'"


def zsh_completion() -> str:
    excluded = _exclusive()
    specs = " \\\n        ".join(_zsh_spec(a, excluded) for a in _actions())
    return f"""#compdef {PROG}
# zsh completion for {PROG} -- {HEADER.format(name="zsh")}

_pydebuprep_cleanup_packages() {{
    local -a packages
    packages=(${{(f)"$({PACKAGES})"}})
    compadd -a packages
}}

_pydebuprep_cleanup() {{
    _arguments -s -S \\
        {specs}
}}

if [[ $zsh_eval_context[-1] == loadautofunc ]]; then
    _pydebuprep_cleanup "$@"
else
    compdef _pydebuprep_cleanup {PROG}
fi
"""


def main(argv: list[str]) -> int:
    scripts = {"bash": bash_completion, "zsh": zsh_completion}
    if len(argv) != 1 or argv[0] not in scripts:
        print("usage: main(['bash']) or main(['zsh'])", file=sys.stderr)
        return 2
    print(scripts[argv[0]](), end="")
    return 0
